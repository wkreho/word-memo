export const deckLayout = 2;

export function migrateProgress(saved) {
  if (saved.deckLayout === deckLayout) return saved;

  const selected = new Set(Array.isArray(saved.selected) ? saved.selected : []);
  const checked = new Set(Array.isArray(saved.checked) ? saved.checked : []);
  const oldChecks = new Set(checked);

  for (const { id, count, sources } of consolidatedDecks) {
    const allChecked = Array(count).fill(true);
    let wasSelected = false;

    for (const [oldId, positions] of Object.entries(sources)) {
      if (selected.delete(oldId)) wasSelected = true;
      positions.forEach((newIndex, oldIndex) => {
        const oldKey = oldId + ':' + oldIndex;
        if (!oldChecks.has(oldKey)) allChecked[newIndex] = false;
        checked.delete(oldKey);
      });
    }

    if (wasSelected) selected.add(id);
    allChecked.forEach((complete, index) => {
      if (complete) checked.add(id + ':' + index);
    });
  }

  return { ...saved, deckLayout, selected: [...selected], checked: [...checked] };
}
